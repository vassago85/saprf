                <h2>3. Personal Information We Collect</h2>
                <p>We collect the following categories of personal information:</p>

                <h3>3.1 Account &amp; Identity</h3>
                <ul>
                    <li>Full name</li>
                    <li>Email address</li>
                    <li>Password (stored in hashed form only)</li>
                    <li>South African ID number (optional, used for age verification and membership compliance)</li>
                    <li>Date of birth</li>
                    <li>Province of residence</li>
                    <li>Phone number (optional)</li>
                </ul>

                <h3>3.2 Membership</h3>
                <ul>
                    <li>SAPRF membership number</li>
                    <li>Membership type and status</li>
                    <li>Payment status and payment references (we do not store banking or card details)</li>
                    <li>Membership start and expiry dates</li>
                </ul>

                <h3>3.3 Competition &amp; Performance</h3>
                <ul>
                    <li>Match registrations and attendance</li>
                    <li>Scores, rankings, and standings</li>
                    <li>Division classification</li>
                    <li>Rifle configurations and ammunition load data</li>
                </ul>

                <h3>3.4 Technical</h3>
                <ul>
                    <li>Session cookies (authentication and CSRF protection only)</li>
                    <li>IP address and browser information (server access logs)</li>
                </ul>

                <h2>4. Legal Basis for Processing</h2>
                <p>Under POPIA, we process your personal information on the following grounds:</p>
                <ul>
                    <li><strong>Contractual necessity (Section 11(1)(b)):</strong> Processing required to fulfil your membership agreement and competition participation.</li>
                    <li><strong>Legitimate interest (Section 11(1)(f)):</strong> Federation administration, maintaining accurate competition records, and ensuring fair play.</li>
                    <li><strong>Legal obligation (Section 11(1)(c)):</strong> Compliance with sports governance requirements and reporting obligations (e.g., SASCOC).</li>
                    <li><strong>Consent (Section 11(1)(a)):</strong> Where you voluntarily provide optional information such as your SA ID number, phone number, or equipment details.</li>
                </ul>

                <h2>5. How We Use Your Information</h2>
                <ul>
                    <li>Register and manage your SAPRF membership</li>
                    <li>Process match registrations and record competition results</li>
                    <li>Calculate and publish rankings, standings, and season results</li>
                    <li>Send transactional emails (registration confirmations, membership notices, match updates)</li>
                    <li>Generate reports required by sports governance bodies</li>
                    <li>Maintain audit trails for administrative actions</li>
                    <li>Improve the Platform and resolve technical issues</li>
                </ul>

                <h2>6. Public Display of Information</h2>
                <p>The following information is publicly visible on the Platform to all visitors without authentication:</p>
                <ul>
                    <li>Your <strong>name</strong>, <strong>province</strong>, and <strong>division</strong> in match results and season standings</li>
                    <li>Your <strong>match scores</strong>, <strong>rankings</strong>, and <strong>normalised season points</strong></li>
                </ul>
                <p>This public display is integral to the operation of a competitive sports federation and is based on legitimate interest. Your email address, SA ID number, date of birth, and contact details are <strong>never</strong> publicly displayed.</p>

