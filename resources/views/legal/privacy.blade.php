                <h2>8. Data Retention</h2>
                <ul>
                    <li><strong>Active accounts:</strong> Personal information is retained for the duration of your membership and account activity.</li>
                    <li><strong>After account closure:</strong> Core identity data is retained for 2 years after your last active membership to facilitate re-registration and resolve any disputes.</li>
                    <li><strong>Competition records:</strong> Scores, rankings, and standings are retained indefinitely as part of the Federation's official historical record. This is standard practice for sports governing bodies.</li>
                    <li><strong>Audit logs:</strong> Administrative action logs are retained for 5 years for governance and compliance purposes.</li>
                    <li><strong>Server logs:</strong> Technical access logs are retained for up to 90 days.</li>
                </ul>

                <h2>9. Data Security</h2>
                <p>We implement appropriate technical and organisational measures to protect your personal information, including:</p>
                <ul>
                    <li>Encrypted connections (HTTPS/TLS) for all data in transit</li>
                    <li>Hashed password storage using industry-standard algorithms</li>
                    <li>Role-based access controls limiting who can view and modify data</li>
                    <li>Regular software updates and security patches</li>
                    <li>Server-level firewalls and access restrictions</li>
                </ul>

                <h2>10. Cookies</h2>
                <p>The Platform uses only <strong>essential session cookies</strong> required for authentication and security (CSRF protection). We do not use tracking cookies, analytics cookies, or advertising cookies. No third-party cookie-based tracking is present on the Platform.</p>

                <h2>11. Your Rights Under POPIA</h2>
                <p>As a data subject, you have the right to:</p>
                <ul>
                    <li><strong>Access</strong> your personal information held by us</li>
                    <li><strong>Correct</strong> any inaccurate or incomplete personal information</li>
                    <li><strong>Delete</strong> your personal information, subject to our legal retention obligations and the legitimate interest in maintaining competition records</li>
                    <li><strong>Object</strong> to the processing of your personal information on reasonable grounds</li>
                    <li><strong>Withdraw consent</strong> where processing is based on consent, without affecting the lawfulness of prior processing</li>
                    <li><strong>Lodge a complaint</strong> with the Information Regulator of South Africa</li>
                </ul>
                <p>To exercise any of these rights, contact us at <a href="mailto:privacy@saprf.co.za">privacy@saprf.co.za</a>. We will respond within 30 days as required by POPIA.</p>

                <h2>12. Children's Information</h2>
                <p>The Platform may be used by persons under the age of 18 (junior and sub-junior competitors). Accounts for minors must be created with the knowledge and consent of a parent or legal guardian. We process minors' information on the same basis as adult members, with the additional safeguard that a parent or guardian may exercise data subject rights on behalf of the minor.</p>

